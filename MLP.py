class ReLU:
    @staticmethod
    def forward(x):
        return np.maximum(0, x)

    @staticmethod
    def derivative(x):
        return (x > 0).astype(float)


class LeakyReLU:
    @staticmethod
    def forward(x, alpha=0.01):
        return np.where(x > 0, x, alpha * x)

    @staticmethod
    def derivative(x, alpha=0.01):
        return np.where(x > 0, 1.0, alpha)


class Sigmoid:
    @staticmethod
    def forward(x):
        x = np.clip(x, -500, 500)
        return 1 / (1 + np.exp(-x))

    @staticmethod
    def derivative(x):
        s = Sigmoid.forward(x)
        return s * (1 - s)


class Tanh:
    @staticmethod
    def forward(x):
        return np.tanh(x)

    @staticmethod
    def derivative(x):
        return 1 - np.tanh(x) ** 2


class Softmax:

    @staticmethod
    def forward(x):

        # estabilidad numérica
        x = x - np.max(x)

        exp_x = np.exp(x)

        return exp_x / np.sum(exp_x)

    @staticmethod
    def derivative(x):
        raise NotImplementedError(
            "Softmax se usa junto con CrossEntropy."
        )


ACTIVACIONES = {
    "relu": ReLU,
    "leaky_relu": LeakyReLU,
    "sigmoide": Sigmoid,
    "tanh": Tanh,
    "softmax": Softmax
}

# ==========================================================
# FUNCIONES DE PÉRDIDA
# ==========================================================

class MSE:
    @staticmethod
    def loss(y_true, y_pred):
        return 0.5 * np.sum((y_true - y_pred) ** 2) / len(y_true)

    @staticmethod
    def derivative(y_true, y_pred):
        return (y_pred - y_true) / len(y_true)

class CrossEntropy:

    @staticmethod
    def loss(y_true, y_pred):

        y_pred = np.clip(
            y_pred,
            1e-15,
            1 - 1e-15
        )

        return -np.sum(
            y_true * np.log(y_pred)
        )

    @staticmethod
    def derivative(y_true, y_pred):

        y_pred = np.clip(
            y_pred,
            1e-15,
            1 - 1e-15
        )

        return y_pred - y_true

PERDIDAS = {
    "mse": MSE,
    "cross_entropy": CrossEntropy
}

